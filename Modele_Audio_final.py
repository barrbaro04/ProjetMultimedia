    def __init__(self, entrees_dev, etiquettes_dev):
        super().__init__()
        self.entrees_dev = entrees_dev
        self.etiquettes_dev = etiquettes_dev

    def on_epoch_end(self, epoch, logs=None):
        # Prédire les émotions sur le développement
        probabilites = self.model(
            self.entrees_dev,
            training=False
        ).numpy()

        predictions = np.argmax(probabilites, axis=1)

        # Ajouter le score aux résultats de l’époque
        if logs is not None:
            logs["val_f1_macro"] = f1_score(
                self.etiquettes_dev,
                predictions,
                labels=np.arange(len(ordre_emotions)),
                average="macro",
                zero_division=0
            )

