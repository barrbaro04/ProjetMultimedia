from torch.utils.data import DataLoader


def predire_torch(modele, jeu, assembleur=default_data_collator,
                  taille_lot=16, precision_mixte=False):
    lecteur = DataLoader(jeu, batch_size=taille_lot, shuffle=False,
        num_workers=0, collate_fn=assembleur)
    modele.to(appareil_ast).eval()
    logits = []
    try:
        with torch.inference_mode():
            for lot in lecteur:
                entrees = {cle: valeur.to(appareil_ast) for cle, valeur in lot.items()
                           if cle != "labels"}
                with torch.autocast(device_type="cuda", dtype=torch.float16, enabled=precision_mixte):
                    sorties = modele(**entrees).logits
                logits.append(sorties.float().cpu().numpy())
    finally:
        modele.to("cpu")
        torch.cuda.empty_cache()
    return np.concatenate(logits)


