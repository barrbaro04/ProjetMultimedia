"""### 19.1. Préparation des données et du CNN

La moyenne et l'écart-type de chaque coefficient sont calculés sur train.
Le réseau comprend trois blocs convolutifs, puis une sortie à huit classes.
La normalisation est enregistrée avec ses poids.

"""

class JeuMFCC(Dataset):
    def __init__(self, valeurs, fenetres, entrainement=False):
        self.valeurs = valeurs
        self.fenetres = fenetres.reset_index(drop=True)
        self.entrainement = entrainement
        self.groupes = list(self.fenetres.groupby("video_id", sort=False).indices.values())

    def __len__(self):
        return len(self.groupes) if self.entrainement else len(self.fenetres)

    def __getitem__(self, indice):
        if self.entrainement:
            groupe = self.groupes[indice]
            indice = int(groupe[torch.randint(len(groupe), (1,)).item()])
        return {"input_values": torch.from_numpy(self.valeurs[indice]).unsqueeze(0),
                "labels": int(self.fenetres.iloc[indice]["label"])}


class ClassifieurMFCC(torch.nn.Module):
    def __init__(self, moyenne, echelle):
        super().__init__()
        self.register_buffer("moyenne", torch.tensor(moyenne, dtype=torch.float32).reshape(1, 1, 40, 1))
        self.register_buffer("echelle", torch.tensor(echelle, dtype=torch.float32).reshape(1, 1, 40, 1))
        self.reseau = torch.nn.Sequential(
            torch.nn.Conv2d(1, 16, 3, padding=1), torch.nn.ReLU(), torch.nn.MaxPool2d(2),
            torch.nn.Conv2d(16, 32, 3, padding=1), torch.nn.ReLU(), torch.nn.MaxPool2d(2),
            torch.nn.Conv2d(32, 64, 3, padding=1), torch.nn.ReLU(),
            torch.nn.AdaptiveAvgPool2d((1, 1)), torch.nn.Flatten(),
            torch.nn.Linear(64, 64), torch.nn.ReLU(), torch.nn.Dropout(0.3),
            torch.nn.Linear(64, len(ordre_emotions))
        )

    def forward(self, input_values, labels=None):
        valeurs = (input_values - self.moyenne) / self.echelle
        return SequenceClassifierOutput(logits=self.reseau(valeurs))


