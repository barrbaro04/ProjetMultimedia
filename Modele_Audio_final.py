def agreger_probabilites_ast(logits, table_fenetres, table_extraits):
    assert logits.shape == (len(table_fenetres), len(ordre_emotions))
    assert np.isfinite(logits).all()

    # Associer chaque fenêtre à la position de son extrait
    identifiants = pd.Index(table_extraits["video_id"])
    indices = identifiants.get_indexer(table_fenetres["video_id"])
    assert (indices >= 0).all()

    probabilites_fenetres = softmax(logits, axis=1)

    # Additionner les probabilités des fenêtres de chaque extrait
    probabilites_extraits = np.zeros(
        (len(table_extraits), len(ordre_emotions)),
        dtype=np.float64
    )
    np.add.at(probabilites_extraits, indices, probabilites_fenetres)

    # Diviser par le nombre de fenêtres de chaque extrait
    nombres_fenetres = np.bincount(
        indices, minlength=len(table_extraits)
    )
    assert (nombres_fenetres > 0).all()

    return probabilites_extraits / nombres_fenetres[:, None]


