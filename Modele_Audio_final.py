def fichier_poids(dossier):
    for nom in ["model.safetensors", "pytorch_model.bin"]:
        chemin = dossier / nom
        if chemin.is_file():
            return chemin
    return None


def trouver_modele(nom):
    dossier = dossier_modeles / nom
    if fichier_poids(dossier / "meilleur") is not None:
        return dossier / "meilleur"

    # Les anciens checkpoints peuvent encore contenir un chemin Colab.
    # On retrouve le dossier local en gardant son nom checkpoint-XXXX.
    candidats = []
    for chemin_etat in dossier.rglob("trainer_state.json"):
        etat = json.loads(chemin_etat.read_text(encoding="utf-8"))
        meilleur = etat.get("best_model_checkpoint")
        score = etat.get("best_metric")
        if meilleur is None or score is None:
            continue
        checkpoint = chemin_etat.parent.parent / Path(meilleur).name
        if fichier_poids(checkpoint) is not None:
            candidats.append((float(score), etat.get("global_step", 0), checkpoint))
    if candidats:
        return max(candidats, key=lambda ligne: (ligne[0], ligne[1]))[2]
    return None


def charger_poids(modele, dossier):
    import torch
    from safetensors.torch import load_file

    chemin = fichier_poids(dossier)
    if chemin is None:
        raise FileNotFoundError(f"Poids absents : {dossier}")
    if chemin.suffix == ".safetensors":
        poids = load_file(str(chemin), device="cpu")
    else:
        poids = torch.load(chemin, map_location="cpu", weights_only=True)
    modele.load_state_dict(poids, strict=True)
    modele.eval()
    return modele


