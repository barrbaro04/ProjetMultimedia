"""### 16.2. Assemblage du modèle

Le modèle transforme le signal audio en caractéristiques,
calcule leur moyenne, applique la standardisation, puis prédit
les huit émotions.

Les statistiques de standardisation restent fixes et proviennent
uniquement de l’apprentissage.

"""

class ModeleEmotionAudio(torch.nn.Module):
    def __init__(self, encodeur, classifieur, standardisation):
        super().__init__()
        self.encodeur = encodeur
        self.classifieur = classifieur

        # Conserver les statistiques dans le modèle
        self.register_buffer(
            "moyenne",
            torch.tensor(standardisation.mean_, dtype=torch.float32)
        )
        self.register_buffer(
            "echelle",
            torch.tensor(standardisation.scale_, dtype=torch.float32)
        )

    def forward(self, input_values, attention_mask=None, labels=None):
        etats = self.encodeur(
            input_values=input_values,
            attention_mask=attention_mask
        ).last_hidden_state.float()

        if attention_mask is None:
            vecteurs = etats.mean(dim=1)
        else:
            masque = self.encodeur._get_feature_vector_attention_mask(
                etats.shape[1], attention_mask
            )
            masque = masque.unsqueeze(-1).to(etats.dtype)

            vecteurs = (
                (etats * masque).sum(dim=1)
                / masque.sum(dim=1).clamp_min(1.0)
            )

        vecteurs = (vecteurs - self.moyenne) / self.echelle
        logits = self.classifieur(vecteurs)

        return SequenceClassifierOutput(logits=logits)


